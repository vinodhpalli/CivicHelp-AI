# app/agents/state.py

from typing import Any, TypedDict


class CivicHelpState(
    TypedDict,
    total=False,
):

    # ========================================================
    # USER QUERY
    # ========================================================

    query: str

    # ========================================================
    # QUERY ROUTING
    # ========================================================

    query_route: dict[str, Any]

    # ========================================================
    # SCHEME
    # ========================================================

    scheme: dict[str, Any]

    # ========================================================
    # USER PROFILE
    # ========================================================

    profile: dict[str, Any]

    # ========================================================
    # NORMAL RAG EVIDENCE
    # ========================================================

    evidence: list[
        dict[str, Any]
    ]

    # ========================================================
    # SCHEME DISCOVERY
    # ========================================================

    discovery_results: list[
        dict[str, Any]
    ]

    discovery_evidence: list[
        dict[str, Any]
    ]

    # ========================================================
    # ELIGIBILITY
    # ========================================================

    eligibility: dict[str, Any]

    # ========================================================
    # EVIDENCE VALIDATION
    # ========================================================

    evidence_validation: dict[str, Any]

    # ========================================================
    # CITATIONS
    # ========================================================

    citations: list[
        dict[str, Any]
    ]

    # ========================================================
    # ANSWER
    # ========================================================

    answer: str

    # ========================================================
    # FINAL RESPONSE
    # ========================================================

    response: dict[str, Any]

    # ========================================================
    # STATUS / MESSAGE
    # ========================================================

    status: str

    message: str